import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createPDF } from '../packages/core/src/pdfcreator.js';
import { buildFidelityHtml } from '../packages/core/src/fidelity.js';

function base64(text) {
  return Buffer.from(text, 'utf8').toString('base64');
}

function pageSvg(page, color) {
  return `
    <svg xmlns="http://www.w3.org/2000/svg" width="612" height="792" viewBox="0 0 612 792">
      <rect width="612" height="792" fill="#fff"/>
      <rect x="48" y="46" width="516" height="92" rx="10" fill="#eaf2ff" stroke="${color}" stroke-width="2"/>
      <text x="72" y="92" font-family="Arial" font-size="27" font-weight="700" fill="#111827">SDK Rendered Accessible PDF HTML</text>
      <text x="72" y="120" font-family="Arial" font-size="13" fill="#374151">Generated by CodbDocs buildFidelityHtml()</text>
      <line x1="72" y1="176" x2="540" y2="176" stroke="#d1d5db" stroke-width="2"/>
      <text x="72" y="220" font-family="Arial" font-size="18" font-weight="700" fill="#111827">What you are seeing</text>
      <text x="92" y="260" font-family="Arial" font-size="14" fill="#111827">1. This page was rendered by the SDK accessible HTML viewer.</text>
      <text x="92" y="292" font-family="Arial" font-size="14" fill="#111827">2. The visual PDF layer remains visible.</text>
      <text x="92" y="324" font-family="Arial" font-size="14" fill="#111827">3. The text layer is searchable, selectable, and reflowable.</text>
      <rect x="72" y="372" width="468" height="126" rx="8" fill="#f9fafb" stroke="#cbd5e1"/>
      <text x="92" y="412" font-family="Arial" font-size="15" fill="#111827">Use the toolbar: PDF view, Reflow, Accessibility, Search.</text>
      <text x="92" y="444" font-family="Arial" font-size="15" fill="#111827">This is the SDK output HTML, saved as a standalone file.</text>
      <text x="92" y="476" font-family="Arial" font-size="15" fill="#111827">No server or import is needed to view this file.</text>
      <text x="72" y="720" font-family="Arial" font-size="12" fill="#6b7280">SDK rendered accessible PDF HTML - page ${page}</text>
    </svg>`;
}

const lines = [
  ['title', 'SDK Rendered Accessible PDF HTML', 27, 72, 792 - 92, 430, 'heading'],
  ['sub', 'Generated by CodbDocs buildFidelityHtml()', 13, 72, 792 - 120, 280, 'paragraph'],
  ['h', 'What you are seeing', 18, 72, 792 - 220, 200, 'heading'],
  ['a', '1. This page was rendered by the SDK accessible HTML viewer.', 14, 92, 792 - 260, 405, 'paragraph'],
  ['b', '2. The visual PDF layer remains visible.', 14, 92, 792 - 292, 275, 'paragraph'],
  ['c', '3. The text layer is searchable, selectable, and reflowable.', 14, 92, 792 - 324, 390, 'paragraph'],
  ['d', 'Use the toolbar: PDF view, Reflow, Accessibility, Search.', 15, 92, 792 - 412, 395, 'paragraph'],
  ['e', 'This is the SDK output HTML, saved as a standalone file.', 15, 92, 792 - 444, 385, 'paragraph'],
  ['f', 'No server or import is needed to view this file.', 15, 92, 792 - 476, 330, 'paragraph'],
];

const ir = {
  version: '1.0',
  document: {
    id: 'sdk-rendered-accessible-pdf',
    title: 'SDK Rendered Accessible PDF HTML',
    metadata: { title: 'SDK Rendered Accessible PDF HTML', language: 'en' },
    pages: ['page_1', 'page_2'],
  },
  pages: {},
  objects: {},
  structure: {},
  annotations: {},
  vectors: {},
  forms: { fields: [], byName: {} },
};

['#0f5fc4', '#b42318'].forEach((color, index) => {
  const pageNum = index + 1;
  const pageId = `page_${pageNum}`;
  ir.pages[pageId] = {
    id: pageId,
    num: pageNum,
    width: 612,
    height: 792,
    rotation: 0,
    mediaBox: [0, 0, 612, 792],
    background: `data:image/svg+xml;base64,${base64(pageSvg(pageNum, color))}`,
    content: [...lines.map((line) => `${pageId}_${line[0]}`), ...(pageNum === 1 ? ['page_1_sample_field'] : [])],
    vectors: [],
    images: [],
    annotations: [],
  };

  lines.forEach(([key, text, size, x, y, width, role]) => {
    const id = `${pageId}_${key}`;
    ir.objects[id] = {
      id,
      type: 'text',
      page: pageId,
      raw: { text, font: 'Arial', fontSize: size, transform: [size, 0, 0, size, x, y] },
      semantic: { role, text },
      accessibility: { role: role === 'heading' ? 'H2' : 'P' },
      bbox: [x, y, width, size + 4],
    };
  });
});

ir.objects.page_1_sample_field = {
  id: 'page_1_sample_field',
  type: 'form_field',
  page: 'page_1',
  raw: {
    fieldName: 'sampleAcknowledgement',
    fieldType: 'checkbox',
    value: '',
    optionValue: 'Yes',
    checked: false,
  },
  semantic: {
    fieldName: 'sampleAcknowledgement',
    fieldType: 'checkbox',
    value: '',
  },
  accessibility: {
    label: 'Sample acknowledgement checkbox',
    required: false,
  },
  bbox: [92, 230, 16, 16],
};

ir.forms.fields.push({
  id: 'page_1_sample_field',
  page: 1,
  name: 'sampleAcknowledgement',
  fieldName: 'sampleAcknowledgement',
  label: 'Sample acknowledgement checkbox',
  fieldType: 'checkbox',
  value: '',
  optionValue: 'Yes',
  checked: false,
});
ir.forms.byName.sampleAcknowledgement = ['page_1_sample_field'];

const originalPdfBytes = await createPDF(ir, { level: 2 });
const originalPdfSrc = `data:application/pdf;base64,${Buffer.from(originalPdfBytes).toString('base64')}`;

const html = buildFidelityHtml(ir, {
  title: 'SDK Rendered Accessible PDF HTML',
  lang: 'en',
  thumbnails: true,
  originalPdfSrc,
  originalUrl: originalPdfSrc,
  originalName: 'sdk-rendered-accessible-pdf.pdf',
  pdfJsUrl: '../vendor/pdf.js/pdf.min.js',
  sourceUrl: 'sdk-rendered-accessible-pdf.pdf',
  permalink: 'sdk-rendered-accessible-pdf.html',
  translate: true,
  priorityLanguages: ['es', 'ht', 'fr'],
  qaEndpoint: '/example-ai-qa-endpoint',
  aiEndpoint: '/example-ai-summary-endpoint',
  improveEndpoint: '/example-improve-endpoint',
  feedbackEmail: 'accessibility@example.com',
  airaUrl: 'https://aira.io/',
  formSubmitEndpoint: '/example-form-submit-endpoint',
  allowPdfSubmitActions: true,
  showDataControls: true,
});

writeFileSync(join(process.cwd(), 'examples', 'sdk-rendered-accessible-pdf.html'), html);
